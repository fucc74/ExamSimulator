#!/usr/bin/env node
// Scans the folder for *.exam files and writes the catalog (exams.js) used by the exam list.
const fs = require('fs');
const path = require('path');
const { ROOT, readExamFile, examFiles } = require('./exam-files.js');

function buildCatalog() {
    return examFiles().map(file => {
        const name = path.basename(file, '.exam');
        let data;
        try { data = readExamFile(file); } catch (e) { console.warn('! ' + path.basename(file) + ': cannot be read (' + e.message + ')'); return null; }
        if (!data) { console.warn('! ' + path.basename(file) + ': registers no exam'); return null; }
        const legacy = data.format === undefined && data.config;
        const title = legacy ? (data.config.examTitle || name) : data.title;
        const description = legacy ? data.config.subtitle : data.description;
        const questions = (data.questions || []);
        const topics = new Set(questions.map(q => q.topic));
        return {
            file: name, id: (legacy ? name : (data.id || name)), title: title || name, description: description || '',
            code: legacy ? data.config.examCode : data.code, version: legacy ? data.config.version : data.version,
            questionCount: questions.length, topicCount: topics.size
        };
    }).filter(Boolean);
}

function writeCatalogFile(catalog) {
    const header = '// Generated by tools/make-manifest.js (run `npm run build`). Optional: exam.html also has this list built in.\n';
    fs.writeFileSync(path.join(ROOT, 'exams.js'), header + 'window.ExamCatalog = ' + JSON.stringify(catalog, null, 2) + ';\n');
}

module.exports = { buildCatalog, writeCatalogFile };

if (require.main === module) {
    const c = buildCatalog();
    writeCatalogFile(c);
    console.log('exams.js written with ' + c.length + ' exam(s): ' + c.map(e => e.file).join(', '));
}
