App.lang = 'en';
App.setLang = function (l) { App.lang = (l === 'it') ? 'it' : 'en'; };

App.t = function (key, params) {
    let s = (App.I18N[App.lang] && App.I18N[App.lang][key]) || App.I18N.en[key] || key;
    Object.keys(params || {}).forEach(k => { s = s.split('{' + k + '}').join(params[k]); });
    return s;
};

// Localized content value: string | {en,it,...} -> string in the current language
App.loc = function (v) {
    if (v === undefined || v === null) return '';
    if (typeof v === 'string' || typeof v === 'number') return String(v);
    return v[App.lang] || v.en || Object.values(v)[0] || '';
};
